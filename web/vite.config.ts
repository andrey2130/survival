import { defineConfig, type Plugin } from 'vite';
import { viteSingleFile } from 'vite-plugin-singlefile';
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const pkg = JSON.parse(readFileSync(resolve(import.meta.dirname, 'package.json'), 'utf8')) as { version: string };
const sha = (() => { try { return execSync('git rev-parse --short HEAD').toString().trim(); } catch { return 'local'; } })();
const VERSION = `${pkg.version}+${sha}`;
const DATE = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';

/**
 * Service worker with a cache name unique to this build, so an installed PWA on iPhone always picks up
 * the new version: network-first for the page, cache only as an offline fallback, old caches deleted.
 */
function serviceWorker(): Plugin {
  return {
    name: 'frostwood-sw',
    apply: 'build',
    closeBundle() {
      const sw = `// generated by vite.config.ts — do not edit
const CACHE = 'frostwood-${VERSION}-${Date.now()}';
self.addEventListener('install', (e) => { self.skipWaiting(); e.waitUntil(caches.open(CACHE).then((c) => c.addAll(['./', './index.html']))); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return r; }).catch(() => caches.match(e.request).then((r) => r || caches.match('./index.html'))));
});
`;
      writeFileSync(resolve(import.meta.dirname, 'dist/sw.js'), sw);
    },
  };
}

// Single-file output so the iOS WKWebView can load one bundled HTML without path issues.
export default defineConfig({
  base: './',
  plugins: [viteSingleFile(), serviceWorker()],
  define: { __APP_VERSION__: JSON.stringify(VERSION), __BUILD_DATE__: JSON.stringify(DATE) },
  build: { target: 'es2020', assetsInlineLimit: 100000000, chunkSizeWarningLimit: 4000 },
});
